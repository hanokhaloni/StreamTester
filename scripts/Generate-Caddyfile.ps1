<#
.SYNOPSIS
  Generates the Caddyfile for the HTTP/2 comparison. Caddy serves the same
  static web/ UI on both a plain-HTTP listener (used by mode A, direct
  MediaMTX fetch, no proxy involved) and a TLS/HTTP-2 listener (mode B) that
  reverse-proxies the full HLS path tree (playlists, init segments, media
  segments, LL-HLS parts, and their query strings) to whichever MediaMTX
  profile is currently active.

.NOTES
  CORS for mode A is handled by MediaMTX itself (hlsAllowOrigins: ["*"] in
  the generated config) since the UI origin (plain HTTP) and the stream
  origin (MediaMTX's own HTTP server) differ. In mode B, UI and stream share
  one origin (this Caddy HTTPS listener), so no CORS header is required for
  the proxied path -- one is still added defensively.

  `tls internal` makes Caddy mint its own local CA and a leaf cert for this
  host on first use (stored under Caddy's data dir, not the Windows cert
  store). Caddy is NOT told to auto-trust that CA system-wide; that step
  needs explicit user approval (see README) and is done manually with
  `certutil -user -addstore Root <path>` against the CurrentUser store, which
  does not require admin.
#>
param(
    [ValidateSet("ondemand","remux")][string]$Profile = "ondemand"
)
. "$PSScriptRoot\Lab.Config.ps1"
$p = Get-LabProfile -Profile $Profile

$webRoot = ($Lab.Dirs.Web -replace '\\','/')
$hlsUpstream = $p.HlsAddress

$caddyfile = @"
# GENERATED by scripts/Generate-Caddyfile.ps1 -- re-run instead of hand-editing.
# Proxies to profile: $Profile (hlsAlwaysRemux=$($p.HlsAlwaysRemux)) at $hlsUpstream
{
	admin 127.0.0.1:19019
	auto_https disable_redirects
	skip_install_trust
}

http://$($Lab.Proxy.HttpAddress) {
	root * `"$webRoot`"
	file_server
	encode gzip
	header Access-Control-Allow-Origin "*"
}

https://$($Lab.Proxy.HttpsAddress) {
	tls internal
	root * `"$webRoot`"
	file_server
	encode gzip
	header Access-Control-Allow-Origin "*"

	handle_path /hls/* {
		reverse_proxy $hlsUpstream {
			flush_interval -1
			header_up Host {upstream_hostport}
		}
	}
}
"@

New-Item -ItemType Directory -Force -Path $Lab.Dirs.Proxy | Out-Null
$outFile = Join-Path $Lab.Dirs.Proxy "Caddyfile.generated"
Set-Content -Path $outFile -Value $caddyfile -Encoding utf8
Write-Host "Wrote $outFile (proxying /hls/* -> $hlsUpstream)"
return $outFile

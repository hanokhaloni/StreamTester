<#
.SYNOPSIS
  Generates a minimal MediaMTX YAML config for one of the two lab profiles.

.NOTES
  MediaMTX merges any YAML you supply with its built-in defaults (confirmed by
  reading the shipped tools/mediamtx/mediamtx.yml for v1.21.2) - keys we don't
  set keep their documented default. We only override what the lab needs.

  Path semantics (confirmed from the same default file, not assumed):
    - `sourceOnDemand` / `runOnDemand` (per-path) only matter when MediaMTX
      itself pulls or spawns a source. Our FFmpeg processes PUSH via RTSP
      continuously, so those settings are irrelevant here and are left at
      default (false) on every stream path.
    - `hlsAlwaysRemux` is a top-level, server-global HLS setting: when false,
      the HLS muxer for a path is created lazily on the first HLS request and
      closed after `hlsMuxerCloseAfter` of inactivity (cold start cost paid by
      the first viewer(s)); when true, the muxer runs continuously as soon as
      the path has a source, regardless of readers (cold start cost paid once,
      at source-start time, off the viewer's critical path). This is the one
      axis that differs between the lab's two MediaMTX profiles/instances.
#>
param(
    [Parameter(Mandatory)][ValidateSet("ondemand","remux")][string]$Profile,
    [int]$StreamCount = 10,
    [ValidateSet("mpegts","lowLatency")][string]$HlsVariant = "mpegts",
    [switch]$EnableRecordingDemo,   # adds 2 extra paths with record:true for the recorded-playback investigation
    [string]$OutFile
)

. "$PSScriptRoot\Lab.Config.ps1"
$p = Get-LabProfile -Profile $Profile

if (-not $OutFile) {
    $OutFile = Join-Path $Lab.Dirs.Generated "mediamtx.$Profile.yml"
}
New-Item -ItemType Directory -Force -Path (Split-Path $OutFile) | Out-Null
New-Item -ItemType Directory -Force -Path $Lab.Dirs.Logs | Out-Null

$logFile = (Join-Path $Lab.Dirs.Logs "mediamtx-$Profile.log") -replace '\\','/'

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("# GENERATED by scripts/Generate-MediaMTXConfig.ps1 -- do not hand-edit, re-run instead.")
[void]$sb.AppendLine("# Profile: $($p.Name) -- $($p.Description)")
[void]$sb.AppendLine("logLevel: info")
[void]$sb.AppendLine("logDestinations: [stdout, file]")
[void]$sb.AppendLine("logFile: $logFile")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("api: true")
[void]$sb.AppendLine("apiAddress: $($p.ApiAddress)")
[void]$sb.AppendLine("apiAllowOrigins: [`"*`"]")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("metrics: true")
[void]$sb.AppendLine("metricsAddress: $($p.MetricsAddress)")
[void]$sb.AppendLine("metricsAllowOrigins: [`"*`"]")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("playback: true")
[void]$sb.AppendLine("playbackAddress: $($p.PlaybackAddress)")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("pprof: false")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("rtsp: true")
[void]$sb.AppendLine("rtspAddress: $($p.RtspAddress)")
[void]$sb.AppendLine("rtspTransports: [tcp]")
[void]$sb.AppendLine("rtspEncryption: `"no`"")
[void]$sb.AppendLine("rtmp: false")
[void]$sb.AppendLine("webrtc: false")
[void]$sb.AppendLine("srt: false")
[void]$sb.AppendLine("moq: false")   # defaults to true and binds :8892/:8893 on all interfaces; not needed, violates loopback-only policy
[void]$sb.AppendLine("")
[void]$sb.AppendLine("hls: true")
[void]$sb.AppendLine("hlsAddress: $($p.HlsAddress)")
[void]$sb.AppendLine("hlsAllowOrigins: [`"*`"]")
[void]$sb.AppendLine("hlsAlwaysRemux: $(if ($p.HlsAlwaysRemux) {'true'} else {'false'})")
[void]$sb.AppendLine("hlsVariant: $HlsVariant")
[void]$sb.AppendLine("hlsSegmentCount: 7")
[void]$sb.AppendLine("hlsSegmentDuration: 1s")
[void]$sb.AppendLine("hlsPartDuration: 200ms")
[void]$sb.AppendLine("hlsMuxerCloseAfter: 60s")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("paths:")
for ($i = 1; $i -le $StreamCount; $i++) {
    $name = "cam{0:D2}" -f $i
    [void]$sb.AppendLine("  ${name}:")
    [void]$sb.AppendLine("    source: publisher")
}
if ($EnableRecordingDemo) {
    foreach ($name in @("rec01","rec02")) {
        [void]$sb.AppendLine("  ${name}:")
        [void]$sb.AppendLine("    source: publisher")
        [void]$sb.AppendLine("    record: true")
        [void]$sb.AppendLine("    recordPath: $((Join-Path $Lab.Dirs.Recordings '%path/%Y-%m-%d_%H-%M-%S-%f') -replace '\\','/')")
        [void]$sb.AppendLine("    recordFormat: fmp4")
        [void]$sb.AppendLine("    recordSegmentDuration: 20s")
        [void]$sb.AppendLine("    recordDeleteAfter: 1h")
    }
}

Set-Content -Path $OutFile -Value $sb.ToString() -NoNewline -Encoding utf8
Write-Host "Wrote $OutFile ($StreamCount stream paths, hlsAlwaysRemux=$($p.HlsAlwaysRemux), hlsVariant=$HlsVariant)"
return $OutFile
